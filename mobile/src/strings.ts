export type Lang = "bn" | "en";
export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, bn };

/** "{done} of {total}" → filled in. A missing value keeps its {placeholder}, so a mistake shows instead of hiding. */
export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const raw = STRINGS[lang][key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}

/** The error codes the server sends (worker/src/lib/http.ts) that have their own words; anything else is "server". */
export function errorKey(code: string | undefined): StringKey {
  const key = `err.${code ?? ""}` as StringKey;
  return key in en ? key : "err.server";
}
