#!/usr/bin/env node
/**
 * Generates worker/.wrangler.dev.toml from worker/wrangler.toml for local development and tests.
 *
 * Why: the [ai] and [stream] bindings are "remote-only" — wrangler would need a Cloudflare login
 * (and could incur usage) even for `wrangler dev`/vitest. The Worker treats both as optional, so the
 * generated copy simply drops them and switches the public vars to development values.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, "worker/wrangler.toml");
const out = resolve(root, "worker/.wrangler.dev.toml");

const DEV_VARS = {
  ENVIRONMENT: "development",
  SITE_URL: "http://localhost:8787",
  PAYMENT_MODE: "sandbox",
};
const DROP_TABLES = new Set(["ai", "stream"]);

const lines = readFileSync(src, "utf8").split("\n");
const result = [];
let dropping = false;
let inVars = false;

for (const line of lines) {
  const header = line.match(/^\s*\[{1,2}\s*([^\]]+?)\s*\]{1,2}\s*(#.*)?$/);
  if (header) {
    const name = header[1];
    dropping = DROP_TABLES.has(name);
    inVars = name === "vars";
    if (dropping) continue;
  } else if (dropping) {
    // skip the body of a dropped table until the next header
    continue;
  }
  if (inVars) {
    const kv = line.match(/^(\w+)\s*=\s*"[^"]*"(.*)$/);
    if (kv && kv[1] in DEV_VARS) {
      result.push(`${kv[1]} = "${DEV_VARS[kv[1]]}"${kv[2]}`);
      continue;
    }
  }
  result.push(line);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "# AUTO-GENERATED by scripts/gen-dev-config.mjs — do not edit, do not commit.\n" +
    result.join("\n"),
);
mkdirSync(resolve(root, "dist/static"), { recursive: true });
console.log("wrote", out.replace(root + "/", ""));
